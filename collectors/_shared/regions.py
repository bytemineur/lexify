def _norm(name: str) -> str:
    if not name:
        return ""
    return (name.replace(" ", "").replace("　", "")
            .replace("（", "(").replace("）", ")"))


def resolve(court_name: str):
    """返回 (province, city, confidence)。confidence: 1.0 精确 / 0.8 地市 / 0.6 区县 / 0 未识别"""
    if not court_name:
        return None, None, 0.0
    s = _norm(court_name)

    # 1) 直辖市优先（避免"北京朝阳区"被辽宁"朝阳市"抢走）
    for k, v in MUNICIPALITIES.items():
        if s.startswith(k):
            return v, v, 1.0

    # 2) 省级全称
    for p in PROVINCES:
        if p in s:
            city = _match_city(s)
            return p, city, 1.0

    # 3) 省级简称 + 地名
    for short, full in PROVINCE_SHORT.items():
        if s.startswith(short):
            return full, _match_city(s), 0.9

    # 4) 地级市
    city = _match_city(s)
    if city:
        prov = CITY_TO_PROVINCE.get(city)
        if prov:
            return prov, city, 0.8

    # 5) 区县兜底
    for county, prov in COUNTY_TO_PROVINCE.items():
        if county in s:
            return prov, _nearest_city(county), 0.6

    return None, None, 0.0


def _match_city(s):
    """在字符串里找最长的地级市名（避免'吉林市'被'吉林'误伤等）。"""
    best, best_len = None, 0
    for c in CITY_TO_PROVINCE:
        if c in s and len(c) > best_len:
            best, best_len = c, len(c)
    return best


