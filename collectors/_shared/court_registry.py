def _city_prefix(city):
    """地市名前缀：直辖市已经是「上海市」，不要再补一个「市」。"""
    return city if city.endswith(("市", "县", "区")) or len(city) > 3 else city + "市"


def _district_court_name(province, city, district):
    """区县法院的通行写法。

    直辖市的区法院写作「上海市黄浦区人民法院」，地级市写作「广州市天河区人民法院」，
    海南的省直辖县市直接写作「五指山市人民法院」。
    """
    if city in MUNICIPALITY:
        return "%s%s人民法院" % (city, district)
    if city in ("东莞", "中山"):
        # 不设区的地级市：东莞市第一人民法院 / 中山市第一人民法院
        return "%s市%s人民法院" % (city, district)
    if province == "海南省":
        if city in ("海口", "三亚", "三沙"):
            return "%s市%s人民法院" % (city, district)
        if city == "儋州":
            # 唯一一个「市院 = 中院」的基层法院，名单里给全称
            return "儋州市人民法院"
        # 省直辖县级行政区，法院名就是这个市县自己的名字
        return district + "人民法院"
    return "%s市%s人民法院" % (city, district)


def build_courts():
    """生成全国法院清单。

    返回 [{name, short, province, city, level}]，level ∈ {高院, 中院, 基层, 特殊}
    """
    out = []

    for prov, name in PROVINCE_COURT.items():
        out.append({"name": name, "short": name, "province": prov,
                    "city": "", "level": "高院"})

    for prov in MUNICIPALITY:
        for name in MUNICIPALITY_INTERMEDIATE.get(prov, []):
            out.append({"name": name, "short": name, "province": prov,
                        "city": prov, "level": "中院"})

    for city, name in CITY_COURT.items():
        prov = regions.CITY_TO_PROVINCE[city]
        out.append({"name": name, "short": name, "province": prov,
                    "city": city, "level": "中院"})

    for prov, cities in COUNTIES.items():
        for city, districts in cities.items():
            for d in districts:
                name = _district_court_name(prov, city, d)
                short = SHORT_NAME_OVERRIDE.get(name, name)
                out.append({"name": name, "short": short, "province": prov,
                            "city": city, "level": "基层"})

    for name in SPECIAL:
        out.append({"name": name, "short": name, "province": "", "city": "",
                    "level": "特殊"})

    seen, uniq = set(), []
    for c in out:
        if c["name"] in seen:
            continue
        seen.add(c["name"])
        uniq.append(c)
    return uniq


ALL_COURTS = build_courts()

