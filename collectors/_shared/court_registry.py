PRIORITY_PROVINCES = ("广东省", "广西壮族自治区", "海南省", "福建省",
                      "江苏省", "浙江省", "上海市")


def by_level(level):
    return [c for c in ALL_COURTS if c["level"] == level]


def by_province(province):
    return [c for c in ALL_COURTS if c["province"] == province]


def priority_courts(levels=("基层", "中院", "高院", "特殊")):
    """优先批次的法院（华南 + 江浙沪），按层级筛选。"""
    return [c for c in ALL_COURTS
            if c["province"] in PRIORITY_PROVINCES and c["level"] in levels]


